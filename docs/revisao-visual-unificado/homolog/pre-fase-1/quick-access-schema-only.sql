BEGIN;
CREATE TABLE unificado_auth.user_quick_access (
 user_id text PRIMARY KEY REFERENCES public.usuarios(id),
 enabled boolean NOT NULL DEFAULT false,home boolean NOT NULL DEFAULT false,
 items jsonb NOT NULL CHECK(jsonb_typeof(items)='array'),revision integer NOT NULL DEFAULT 1 CHECK(revision>0),
 updated_by text NOT NULL,updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE unificado_auth.user_quick_access_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id text NOT NULL,
 actor text NOT NULL,before_state jsonb,after_state jsonb NOT NULL,created_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT,INSERT,UPDATE ON unificado_auth.user_quick_access TO mapa_api_login;
GRANT SELECT,INSERT ON unificado_auth.user_quick_access_audit TO mapa_api_login;
GRANT USAGE,SELECT ON SEQUENCE unificado_auth.user_quick_access_audit_id_seq TO mapa_api_login;
COMMIT;
